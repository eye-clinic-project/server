import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';

export interface ReportPdfData {
  reportId: string;
  title: string;
  status: string;
  createdAt: Date;
  sentAt?: Date | null;
  patient: {
    name: string;
    email: string;
    medicalRecordNumber?: string;
    dateOfBirth?: Date | null;
    gender?: string | null;
  };
  doctor: { name: string; clinicName?: string; specialty?: string };
  analysis: {
    date: Date;
    eye?: string;
    statusLabel: string;
    hasDR?: boolean | null;
    gradeLabel?: string | null;
    gradeDescription?: string | null;
    confidence?: number | null;
    modelVersion?: string | null;
    isMock?: boolean;
  };
  review?: {
    confirmedLabel: string;
    aiResultConfirmed: boolean;
    followUpDate?: Date | null;
  } | null;
  notes?: string;
  recommendations?: string;
  image?: Buffer | null;
  gradCam?: Buffer | null;
  disclaimer: string;
}

const fmtDate = (d?: Date | null) => (d ? new Date(d).toISOString().slice(0, 10) : '—');

/** Renders the medical report PDF (FR4.3, FR4.5, NFR19). */
@Injectable()
export class PdfService {
  renderReport(data: ReportPdfData): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({ size: 'A4', margin: 48, info: { Title: data.title } });
      const chunks: Buffer[] = [];
      doc.on('data', (chunk: Buffer) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      const teal = '#0e7490';
      const muted = '#64748b';

      doc.fillColor(teal).fontSize(20).text('RetinaCare', { continued: true }).fillColor(muted).fontSize(11).text('   Diabetic Retinopathy Report');
      doc.moveDown(0.3).fillColor('#0f172a').fontSize(16).text(data.title);
      doc
        .fillColor(muted)
        .fontSize(9)
        .text(
          `Report ${data.reportId} · Created ${fmtDate(data.createdAt)} · ${data.status.toUpperCase()}${data.sentAt ? ` · Sent ${fmtDate(data.sentAt)}` : ''}`,
        );
      doc.moveDown();

      const section = (title: string) => {
        doc.moveDown(0.6).fillColor(teal).fontSize(12).text(title.toUpperCase());
        doc
          .moveTo(doc.x, doc.y + 2)
          .lineTo(547, doc.y + 2)
          .strokeColor('#cbd5e1')
          .stroke();
        doc.moveDown(0.5).fillColor('#0f172a').fontSize(10);
      };
      const row = (label: string, value: string) => doc.font('Helvetica-Bold').text(`${label}: `, { continued: true }).font('Helvetica').text(value);

      section('Patient');
      row('Name', data.patient.name);
      row('Patient ID', data.patient.medicalRecordNumber ?? '—');
      row('Date of birth', fmtDate(data.patient.dateOfBirth));
      row('Gender', data.patient.gender ?? '—');

      section('Doctor');
      row('Name', `Dr. ${data.doctor.name}`);
      if (data.doctor.clinicName) row('Clinic', data.doctor.clinicName);
      if (data.doctor.specialty) row('Specialty', data.doctor.specialty);

      section('AI analysis');
      row('Date', fmtDate(data.analysis.date));
      if (data.analysis.eye) row('Eye', data.analysis.eye);
      row('Status', data.analysis.statusLabel);
      if (data.analysis.hasDR !== null && data.analysis.hasDR !== undefined) {
        row('DR detected', data.analysis.hasDR ? 'Yes' : 'No');
      }
      if (data.analysis.gradeLabel) row('Severity grade', data.analysis.gradeLabel);
      if (data.analysis.gradeDescription) row('Meaning', data.analysis.gradeDescription);
      if (data.analysis.confidence !== null && data.analysis.confidence !== undefined) {
        row('Confidence', `${Math.round(data.analysis.confidence * 100)}%`);
      }
      if (data.analysis.modelVersion) row('Model', data.analysis.modelVersion);
      if (data.analysis.isMock) {
        doc.fillColor('#b91c1c').text('DEMO RESULT generated by a mock model. Not a real prediction.').fillColor('#0f172a');
      }

      if (data.review) {
        section('Doctor review');
        row('Confirmed grade', data.review.confirmedLabel);
        row('AI result confirmed', data.review.aiResultConfirmed ? 'Yes' : 'No');
        if (data.review.followUpDate) row('Follow-up', fmtDate(data.review.followUpDate));
      }

      if (data.image || data.gradCam) {
        section('Images');
        const top = doc.y;
        const width = 230;
        if (data.image) {
          try {
            doc.image(data.image, 48, top, { fit: [width, width] });
            doc
              .fontSize(8)
              .fillColor(muted)
              .text('Fundus image', 48, top + width + 4);
          } catch {
            doc.text('Fundus image could not be embedded.');
          }
        }
        if (data.gradCam) {
          try {
            doc.image(data.gradCam, 48 + width + 20, top, { fit: [width, width] });
            doc
              .fontSize(8)
              .fillColor(muted)
              .text('Grad-CAM heatmap', 48 + width + 20, top + width + 4);
          } catch {
            /* ignore */
          }
        } else {
          doc
            .fontSize(9)
            .fillColor(muted)
            .text('Grad-CAM heatmap not available.', 48 + width + 20, top + 10);
        }
        doc.x = 48;
        doc.y = top + width + 24;
        doc.fillColor('#0f172a').fontSize(10);
      }

      if (data.notes) {
        section('Doctor notes');
        doc.text(data.notes);
      }
      if (data.recommendations) {
        section('Recommendations');
        doc.text(data.recommendations);
      }

      doc.moveDown(1.2).fontSize(9).fillColor('#b45309').text(data.disclaimer, { align: 'left' });
      doc.end();
    });
  }
}
